/* Optional real-browser check: playwright-core and an installed Chromium. */
const {chromium} = require('playwright-core');
const assert = require('node:assert/strict');
const {pathToFileURL} = require('node:url');
const path = require('node:path');
const {selectAudio} = require('./audio-fixture.cjs');
(async () => {
  const browser = await chromium.launch({headless: true, executablePath: process.env.CODS_BROWSER_PATH || undefined});
  try {
    const page = await browser.newPage({viewport: {width: 1100, height: 1050}, reducedMotion: 'reduce'});
    const errors = [];
    const network = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('request', request => {if (/^https?:/.test(request.url())) network.push(request.url());});
    await page.goto(pathToFileURL(path.resolve(__dirname, '../glyphs/preview.html')).href);
    await page.waitForFunction(() => previews.length === 6 && previews.every(p => p.images.get(p.key)?.ready));
    assert.equal(await page.locator('#voice').getAttribute('src'), null);
    await page.evaluate(() => {
      window.revokedAudioUrls=[];
      const revoke=URL.revokeObjectURL.bind(URL);
      URL.revokeObjectURL=url=>{window.revokedAudioUrls.push(url);revoke(url);};
    });
    await selectAudio(page);
    const firstAudioUrl=await page.locator('#voice').getAttribute('src');
    assert.match(firstAudioUrl,/^blob:/);
    assert.equal(await page.locator('.expression-card').count(), 6);
    assert.equal(await page.locator('#previous').isDisabled(), true);
    await page.getByRole('button', {name: 'Try thinking expression', exact: true}).click();
    assert.equal(await page.locator('#status').textContent(), 'Neutral · Thinking');
    await page.getByRole('button', {name: 'Idle', exact: true}).click();
    await page.locator('#expression-carousel').evaluate(el => { el.scrollLeft = 0; });
    await page.locator('#next').click();
    assert.ok(await page.locator('#expression-carousel').evaluate(el => el.scrollLeft > 0));
    await page.getByRole('button', {name: 'Try skeptical expression', exact: true}).click();
    assert.equal(await page.locator('#status').textContent(), 'Skeptical · Idle');
    await page.getByRole('button', {name: 'Listening', exact: true}).click();
    await page.locator('#voice').evaluate(audio => audio.play());
    await page.waitForFunction(() => document.querySelector('#status').textContent === 'Skeptical · Talking');
    assert.equal(await page.getByRole('button', {name: 'Thinking', exact: true}).isDisabled(), true);
    await page.locator('#voice').evaluate(audio => audio.pause());
    assert.equal(await page.locator('#status').textContent(), 'Skeptical · Listening');
    assert.equal(await page.getByRole('button', {name: 'Thinking', exact: true}).isDisabled(), false);
    await page.locator('#voice').evaluate(audio => audio.play());
    await selectAudio(page,'replacement-tone.wav');
    assert.equal(await page.locator('#voice').evaluate(audio => audio.paused),true);
    assert.equal(await page.evaluate(url=>revokedAudioUrls.includes(url),firstAudioUrl),true);
    const secondAudioUrl=await page.locator('#voice').getAttribute('src');
    await page.locator('#audio-file').setInputFiles([]);
    assert.equal(await page.locator('#voice').getAttribute('src'),secondAudioUrl);
    await page.locator('#audio-file').setInputFiles({name:'invalid.wav',mimeType:'audio/wav',buffer:Buffer.from('not an audio recording')});
    await page.waitForFunction(()=>document.querySelector('#error').textContent.includes('could not be played'));
    await selectAudio(page,'recovered-tone.wav');
    await page.locator('#still').uncheck();
    await page.waitForFunction(() => animator.frameRequest !== null && previews.every(p => p.frameRequest !== null));
    await page.locator('#still').check();
    await page.waitForFunction(() => animator.frameRequest === null && previews.every(p => p.frameRequest === null));
    if (process.env.CODS_SCREENSHOT) await page.screenshot({path: process.env.CODS_SCREENSHOT, fullPage: true});
    await page.setViewportSize({width: 390, height: 844});
    await page.locator('#expression-carousel').evaluate(el => { el.scrollLeft = 0; });
    await page.locator('#expression-carousel').focus();
    await page.keyboard.press('ArrowRight');
    assert.ok(await page.locator('#expression-carousel').evaluate(el => el.scrollLeft > 0));
    await page.getByRole('button', {name: 'Try annoyed expression', exact: true}).click();
    assert.equal(await page.locator('#status').textContent(), 'Annoyed · Listening');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
    assert.deepEqual(errors, []);
    assert.deepEqual(network, []);
    assert.equal(await page.locator('#error').textContent(), '');
    console.log('Browser: carousel, mobile keyboard navigation, expression/activity selection, real audio and reduced motion passed.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
